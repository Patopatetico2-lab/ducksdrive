"""
rclone_stats.py - Rclone Remote Control (RC) telemetry and statistics consumer.

Polls the `/core/stats` HTTP endpoint at 1-second intervals using Basic Auth
with ephemeral credentials generated by rclone_daemon. Computes transfer speeds (MB/s),
remaining time ETA in HH:MM:SS, and descriptive status text.
"""

import base64
from collections import deque
import json
import logging
import time
import urllib.error
import urllib.request
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional

from PySide6.QtCore import QThread, Signal

from i18n import tr
from rclone_daemon import RCCredentials, is_path_mounted

logger = logging.getLogger(__name__)


@dataclass
class StatsData:
    """Represents a telemetry snapshot from the Rclone RC API."""
    is_online: bool
    speed_bytes_per_sec: float = 0.0
    speed_mb_s: float = 0.0
    speed_str: str = "0.00 MB/s"
    eta_seconds: Optional[int] = None
    eta_str: str = "--:--:--"
    # NOTE: rclone's `transfers` is the CUMULATIVE number of files already transferred,
    # NOT the number of active ones. Never use it to decide whether a sync is in progress.
    transfers_count: int = 0
    total_bytes_transferred: int = 0
    total_bytes_str: str = "0 B"
    errors_count: int = 0
    status_text: str = field(default_factory=lambda: tr("Desconectado"))
    active_transfers: List[Dict[str, Any]] = field(default_factory=list)
    recent_transfers: List[Dict[str, Any]] = field(default_factory=list)
    vfs_queue_count: int = 0
    raw_data: Dict[str, Any] = field(default_factory=dict)

    @property
    def has_active_transfers(self) -> bool:
        """True while rclone reports active transfers or files waiting in the VFS upload queue."""
        return self.is_online and (len(self.active_transfers) > 0 or self.vfs_queue_count > 0)


def format_bytes(num_bytes: int) -> str:
    """
    Formats a raw byte count into human-readable units (B, KB, MB, GB, TB).

    Args:
        num_bytes: The number of bytes.

    Returns:
        str: Human-readable string.
    """
    if num_bytes < 0:
        return "0 B"
    for unit in ("B", "KB", "MB", "GB", "TB", "PB"):
        if num_bytes < 1024.0:
            return f"{num_bytes:.2f} {unit}" if unit != "B" else f"{int(num_bytes)} B"
        num_bytes /= 1024.0
    return f"{num_bytes:.2f} PB"


def format_eta(eta_seconds: Optional[int]) -> str:
    """
    Formats an ETA in seconds into HH:MM:SS format.

    Args:
        eta_seconds: Estimated remaining seconds, or None.

    Returns:
        str: Formatted ETA string (e.g., '01:15:30' or '--:--:--').
    """
    if eta_seconds is None or eta_seconds < 0:
        return "--:--:--"

    hours = eta_seconds // 3600
    minutes = (eta_seconds % 3600) // 60
    seconds = eta_seconds % 60
    return f"{hours:02d}:{minutes:02d}:{seconds:02d}"


def _get_auth_header(creds: RCCredentials) -> str:
    """Returns the pre-computed Basic Auth header from RCCredentials."""
    if getattr(creds, "auth_header", ""):
        return creds.auth_header
    auth_str = f"{creds.user}:{creds.password}"
    b64_auth = base64.b64encode(auth_str.encode("utf-8")).decode("ascii")
    return f"Basic {b64_auth}"


def fetch_rclone_stats(creds: RCCredentials, timeout: float = 4.0) -> StatsData:
    """
    Executes a single HTTP POST query to `http://<host>:<port>/core/stats`
    using HTTP Basic Auth.

    Args:
        creds: In-memory credentials for the Rclone RC API.
        timeout: Request timeout in seconds.

    Returns:
        StatsData: Parsed telemetry snapshot.
    """
    endpoint = f"{creds.url}/core/stats"

    req = urllib.request.Request(
        url=endpoint,
        data=b"{}",
        headers={
            "Authorization": _get_auth_header(creds),
            "Content-Type": "application/json",
        },
        method="POST",
    )

    try:
        with urllib.request.urlopen(req, timeout=timeout) as response:
            if response.status == 200:
                raw_json = response.read().decode("utf-8")
                data: Dict[str, Any] = json.loads(raw_json)

                speed_bytes = float(data.get("speed", 0.0))
                speed_mb_s = speed_bytes / (1024.0 * 1024.0)
                speed_str = f"{speed_mb_s:.2f} MB/s"

                raw_eta = data.get("eta")
                eta_seconds = int(raw_eta) if raw_eta is not None else None
                eta_str = format_eta(eta_seconds)

                transfers = int(data.get("transfers", 0))
                active_transfers = data.get("transferring") or []
                total_bytes = int(data.get("bytes", 0))
                errors = int(data.get("errors", 0))

                # Determine high-level descriptive status
                if len(active_transfers) > 0:
                    status_text = tr("Sincronizando (%d ativo(s)) • %s • ETA %s") % (
                        len(active_transfers),
                        speed_str,
                        eta_str,
                    )
                elif errors > 0:
                    status_text = tr("Ocioso com %d erro(s)") % errors
                else:
                    status_text = tr("Sincronizado / Ocioso")

                return StatsData(
                    is_online=True,
                    speed_bytes_per_sec=speed_bytes,
                    speed_mb_s=speed_mb_s,
                    speed_str=speed_str,
                    eta_seconds=eta_seconds,
                    eta_str=eta_str,
                    transfers_count=transfers,
                    total_bytes_transferred=total_bytes,
                    total_bytes_str=format_bytes(total_bytes),
                    errors_count=errors,
                    status_text=status_text,
                    active_transfers=active_transfers,
                    raw_data=data,
                )

    except urllib.error.HTTPError as http_err:
        logger.debug("HTTP error polling rclone stats: %s", http_err)
    except urllib.error.URLError as url_err:
        logger.debug("Connection error polling rclone stats: %s", url_err)
    except Exception as exc:
        logger.debug("Unexpected error polling rclone stats: %s", exc)

    return StatsData(is_online=False, status_text=tr("Drive não conectado"))


def fetch_rclone_transferred(creds: RCCredentials, timeout: float = 2.0) -> List[Dict[str, Any]]:
    """
    Executes a single HTTP POST query to `http://<host>:<port>/core/transferred`
    using HTTP Basic Auth.

    Args:
        creds: In-memory credentials for the Rclone RC API.
        timeout: Request timeout in seconds.

    Returns:
        List[Dict[str, Any]]: List of completed transfer items.
    """
    endpoint = f"{creds.url}/core/transferred"
    req = urllib.request.Request(
        url=endpoint,
        data=b"{}",
        headers={
            "Authorization": _get_auth_header(creds),
            "Content-Type": "application/json",
        },
        method="POST",
    )
    try:
        with urllib.request.urlopen(req, timeout=timeout) as response:
            if response.status == 200:
                raw_json = response.read().decode("utf-8")
                data: Dict[str, Any] = json.loads(raw_json)
                return data.get("transferred") or []
    except Exception as exc:
        logger.debug("Error querying rclone /core/transferred: %s", exc)
    return []


def fetch_vfs_queue(creds: RCCredentials, timeout: float = 2.0) -> Optional[int]:
    """
    Returns how many files are still pending upload in the VFS write-back cache
    (both `uploadsInProgress` and `uploadsQueued` via `vfs/stats`, falling back to `vfs/queue`),
    or None if the RC API could not be queried.

    Blocking call: run it outside the GUI thread.
    """
    headers = {
        "Authorization": _get_auth_header(creds),
        "Content-Type": "application/json",
    }
    req_stats = urllib.request.Request(
        url=f"{creds.url}/vfs/stats",
        data=b"{}",
        headers=headers,
        method="POST",
    )
    try:
        with urllib.request.urlopen(req_stats, timeout=timeout) as response:
            if response.status == 200:
                data: Dict[str, Any] = json.loads(response.read().decode("utf-8"))
                disk_cache = data.get("diskCache")
                if isinstance(disk_cache, dict):
                    in_prog = int(disk_cache.get("uploadsInProgress") or 0)
                    queued = int(disk_cache.get("uploadsQueued") or 0)
                    return in_prog + queued
    except Exception as exc:
        logger.debug("Could not query vfs/stats: %s", exc)

    req_queue = urllib.request.Request(
        url=f"{creds.url}/vfs/queue",
        data=b"{}",
        headers=headers,
        method="POST",
    )
    try:
        with urllib.request.urlopen(req_queue, timeout=timeout) as response:
            if response.status == 200:
                data = json.loads(response.read().decode("utf-8"))
                return len(data.get("queue") or [])
    except Exception as exc:
        logger.debug("Could not query vfs/queue: %s", exc)
    return None


def rc_vfs_refresh(creds: RCCredentials, timeout: float = 15.0) -> bool:
    """
    Sends a POST request to `/vfs/refresh` via RC to reload the directory cache
    without unmounting. Blocking call: run outside the GUI thread.
    """
    req = urllib.request.Request(
        url=f"{creds.url}/vfs/refresh",
        data=b"{}",
        headers={
            "Authorization": _get_auth_header(creds),
            "Content-Type": "application/json",
        },
        method="POST",
    )
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            return resp.status == 200
    except Exception as exc:
        logger.debug("Failed to refresh VFS directory cache via RC: %s", exc)
        return False


def set_rc_bwlimit(creds: RCCredentials, rate: str, timeout: float = 5.0) -> bool:
    """
    Sets the active bandwidth limit on the running rclone daemon via RC `/core/bwlimit`.

    Blocking call: run it outside the GUI thread.
    """
    req = urllib.request.Request(
        url=f"{creds.url}/core/bwlimit",
        data=json.dumps({"rate": rate}).encode("utf-8"),
        headers={
            "Authorization": _get_auth_header(creds),
            "Content-Type": "application/json",
        },
        method="POST",
    )
    try:
        with urllib.request.urlopen(req, timeout=timeout) as resp:
            return resp.status == 200
    except Exception as exc:
        logger.debug("Failed to set bwlimit via RC: %s", exc)
        return False


class RcloneStatsPoller(QThread):
    """
    Dedicated background worker thread that polls Rclone RC `/core/stats`
    every 1 second and tracks the VFS write-back upload queue.
    """

    stats_updated = Signal(object)  # Emits StatsData instance
    connection_lost = Signal()

    def __init__(
        self,
        credentials: RCCredentials,
        poll_interval: float = 1.0,
        parent: Optional[Any] = None,
        daemon: Optional[Any] = None,
    ) -> None:
        super().__init__(parent)
        self.credentials = credentials
        self.poll_interval = poll_interval
        self.daemon = daemon
        self._running = False
        self._recent_transfers: deque[Dict[str, Any]] = deque(maxlen=10)
        self._seen_transfers_keys: set[str] = set()

    def _is_daemon_mount_alive(self) -> bool:
        """Checks whether the underlying rclone daemon process and mount point are still active."""
        if self.daemon is None:
            return False
        try:
            return bool(self.daemon.is_running() and is_path_mounted(self.daemon.mount_point))
        except Exception:
            return False

    def run(self) -> None:
        """Main polling loop running once per second."""
        self._running = True
        logger.info("Started stats polling thread for %s", self.credentials.url)

        was_online = False
        consecutive_failures = 0
        last_valid_stats: Optional[StatsData] = None
        vfs_queue_count = 0
        last_queue_check = 0.0
        last_listed: Optional[int] = None

        while self._running:
            stats = fetch_rclone_stats(self.credentials, timeout=4.0)
            now = time.monotonic()

            if stats.is_online:
                consecutive_failures = 0
                was_online = True

                # Track directory lookup/creation rate (`listed` counter)
                current_listed = int(stats.raw_data.get("listed", 0))
                listed_delta = max(0, current_listed - last_listed) if last_listed is not None else 0
                last_listed = current_listed

                # Poll VFS upload queue every 2s or when transfers/bursts are active
                should_check_queue = (
                    (now - last_queue_check >= 2.0)
                    or len(stats.active_transfers) > 0
                    or vfs_queue_count > 0
                    or listed_delta > 0
                )
                if should_check_queue:
                    q_len = fetch_vfs_queue(self.credentials, timeout=2.0)
                    if q_len is not None:
                        vfs_queue_count = q_len
                    last_queue_check = now

                    # Track recently completed file transfers
                    transferred_items = fetch_rclone_transferred(self.credentials, timeout=2.0)
                    for item in transferred_items:
                        if not isinstance(item, dict):
                            continue
                        name = item.get("name")
                        if not name or item.get("error"):
                            continue
                        key = f"{name}_{item.get('size', 0)}_{item.get('completed_at', '')}"
                        if key not in self._seen_transfers_keys:
                            self._seen_transfers_keys.add(key)
                            self._recent_transfers.appendleft({
                                "name": name,
                                "size": int(item.get("size") or item.get("bytes") or 0),
                                "completed_at": item.get("completed_at", ""),
                            })
                    if len(self._seen_transfers_keys) > 100:
                        valid_keys = {f"{it['name']}_{it['size']}_{it.get('completed_at', '')}" for it in self._recent_transfers}
                        self._seen_transfers_keys.intersection_update(valid_keys)

                stats.vfs_queue_count = vfs_queue_count
                stats.recent_transfers = list(self._recent_transfers)
                if len(stats.active_transfers) == 0 and vfs_queue_count > 0:
                    stats.status_text = tr("Sincronizando (%d na fila) • %s • ETA %s") % (
                        vfs_queue_count,
                        stats.speed_str,
                        stats.eta_str,
                    )

                last_valid_stats = stats
                self.stats_updated.emit(stats)
            else:
                consecutive_failures += 1
                # If rclone is simply busy with heavy FUSE/VFS locks, do not falsely report "Offline"
                if self._is_daemon_mount_alive() and consecutive_failures < 10:
                    if last_valid_stats is not None:
                        last_valid_stats.recent_transfers = list(self._recent_transfers)
                        self.stats_updated.emit(last_valid_stats)
                elif consecutive_failures >= 3:
                    if was_online:
                        self.connection_lost.emit()
                        was_online = False
                    self.stats_updated.emit(stats)

            # Sleep in small increments for responsive thread termination
            steps = int(self.poll_interval / 0.1)
            for _ in range(max(1, steps)):
                if not self._running:
                    break
                time.sleep(0.1)

        logger.info("Stopped stats polling thread.")

    def stop(self, wait: bool = True) -> None:
        """Stops the polling loop; optionally waits (up to 2s) for thread termination."""
        self._running = False
        if wait:
            self.wait(2000)
