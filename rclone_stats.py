"""
rclone_stats.py - Rclone Remote Control (RC) telemetry and statistics consumer for DucksDrive.

Part of DucksDrive: Modern Rclone GUI & Cloud Drive Client for Linux.
Official Website: https://patopatetico2-lab.github.io/ducksdrive/
Source Repository: https://github.com/Patopatetico2-lab/ducksdrive

Polls the `/core/stats` HTTP endpoint at 1-second intervals using Basic Auth
with ephemeral credentials generated by rclone_daemon. Computes transfer speeds (MB/s),
remaining time ETA in HH:MM:SS, and descriptive status text.
"""

import base64
from collections import deque
import http.client
import json
import logging
import socket
import time
import urllib.error
import urllib.request
from dataclasses import dataclass, field, replace
from typing import Any, Dict, List, Optional

from PySide6.QtCore import QThread, Signal

from i18n import tr
from rclone_daemon import RCCredentials, is_path_mounted

logger = logging.getLogger(__name__)


@dataclass
class StatsData:
    """Represents a telemetry snapshot from the Rclone RC API."""
    is_online: bool
    speed_bytes_per_sec: float = 0.0
    speed_mb_s: float = 0.0
    speed_str: str = "0.00 MB/s"
    eta_seconds: Optional[int] = None
    eta_str: str = "--:--:--"
    # NOTE: rclone's `transfers` is the CUMULATIVE number of files already transferred,
    # NOT the number of active ones. Never use it to decide whether a sync is in progress.
    transfers_count: int = 0
    total_bytes_transferred: int = 0
    total_bytes_str: str = "0 B"
    errors_count: int = 0
    status_text: str = field(default_factory=lambda: tr("Desconectado"))
    active_transfers: List[Dict[str, Any]] = field(default_factory=list)
    recent_transfers: List[Dict[str, Any]] = field(default_factory=list)
    vfs_queue_count: int = 0
    vfs_uploads_in_progress: int = 0
    vfs_uploads_queued: int = 0
    vfs_disk_cache_bytes: int = 0
    is_throttled: bool = False
    raw_data: Dict[str, Any] = field(default_factory=dict)

    @property
    def total_transfers(self) -> int:
        """Alias for cumulative completed transfers count."""
        return self.transfers_count

    @property
    def has_active_transfers(self) -> bool:
        """True while rclone reports active transfers or files waiting in the VFS upload queue."""
        return self.is_online and (len(self.active_transfers) > 0 or self.vfs_queue_count > 0)


def format_bytes(num_bytes: int) -> str:
    """
    Formats a raw byte count into human-readable units (B, KB, MB, GB, TB).

    Args:
        num_bytes: The number of bytes.

    Returns:
        str: Human-readable string.
    """
    if num_bytes < 0:
        return "0 B"
    for unit in ("B", "KB", "MB", "GB", "TB", "PB"):
        if num_bytes < 1024.0:
            return f"{num_bytes:.2f} {unit}" if unit != "B" else f"{int(num_bytes)} B"
        num_bytes /= 1024.0
    return f"{num_bytes:.2f} PB"


def format_eta(eta_seconds: Optional[int]) -> str:
    """
    Formats an ETA in seconds into HH:MM:SS format.

    Args:
        eta_seconds: Estimated remaining seconds, or None.

    Returns:
        str: Formatted ETA string (e.g., '01:15:30' or '--:--:--').
    """
    if eta_seconds is None or eta_seconds < 0:
        return "--:--:--"

    hours = eta_seconds // 3600
    minutes = (eta_seconds % 3600) // 60
    seconds = eta_seconds % 60
    return f"{hours:02d}:{minutes:02d}:{seconds:02d}"


def _get_auth_header(creds: RCCredentials) -> str:
    """Returns the pre-computed Basic Auth header from RCCredentials."""
    if getattr(creds, "auth_header", ""):
        return creds.auth_header
    auth_str = f"{creds.user}:{creds.password}"
    b64_auth = base64.b64encode(auth_str.encode("utf-8")).decode("ascii")
    return f"Basic {b64_auth}"


class UnixHTTPConnection(http.client.HTTPConnection):
    """HTTPConnection over a local Unix domain socket."""

    def __init__(self, socket_path: str, timeout: float = 5.0) -> None:
        super().__init__("localhost", timeout=timeout)
        self.socket_path = socket_path

    def connect(self) -> None:
        self.sock = socket.socket(socket.AF_UNIX, socket.SOCK_STREAM)
        self.sock.settimeout(self.timeout)
        self.sock.connect(self.socket_path)


def rc_request(
    creds: RCCredentials,
    endpoint: str,
    data: Optional[Dict[str, Any]] = None,
    timeout: float = 4.0,
) -> tuple[int, Dict[str, Any]]:
    """
    Performs an authenticated POST request against the Rclone RC API.
    Routes via local Unix domain socket if creds.socket_path is set,
    or via TCP HTTP (localhost:port) otherwise.

    Returns:
        tuple[int, Dict[str, Any]]: HTTP status code (200, 401, etc., or 0 on error) and parsed JSON.
    """
    payload = json.dumps(data or {}).encode("utf-8")
    headers = {
        "Authorization": _get_auth_header(creds),
        "Content-Type": "application/json",
    }
    path = endpoint if endpoint.startswith("/") else f"/{endpoint}"

    try:
        if creds.socket_path:
            conn = UnixHTTPConnection(creds.socket_path, timeout=timeout)
            try:
                conn.request("POST", path, body=payload, headers=headers)
                resp = conn.getresponse()
                resp_bytes = resp.read()
                try:
                    res_json = json.loads(resp_bytes.decode("utf-8")) if resp_bytes else {}
                except Exception:
                    res_json = {}
                return resp.status, res_json
            finally:
                conn.close()
        else:
            req = urllib.request.Request(
                url=f"{creds.url}{path}",
                data=payload,
                headers=headers,
                method="POST",
            )
            with urllib.request.urlopen(req, timeout=timeout) as response:
                resp_bytes = response.read()
                try:
                    res_json = json.loads(resp_bytes.decode("utf-8")) if resp_bytes else {}
                except Exception:
                    res_json = {}
                return response.status, res_json
    except urllib.error.HTTPError as http_err:
        try:
            err_body = http_err.read().decode("utf-8")
            err_json = json.loads(err_body)
        except Exception:
            err_json = {}
        logger.debug("RC HTTPError %d on %s: %s", http_err.code, path, http_err)
        return http_err.code, err_json
    except Exception as exc:
        logger.debug("RC request error on %s: %s", path, exc)
        return 0, {}


def fetch_rclone_stats(creds: RCCredentials, timeout: float = 4.0) -> StatsData:
    """
    Executes a telemetry query against `/core/stats` via RC.

    Args:
        creds: In-memory credentials for the Rclone RC API.
        timeout: Request timeout in seconds.

    Returns:
        StatsData: Parsed telemetry snapshot.
    """
    status, data = rc_request(creds, "/core/stats", timeout=timeout)
    if status == 200 and isinstance(data, dict):
        active_transfers = data.get("transferring") or []
        global_speed = float(data.get("speed", 0.0))
        has_per_item_speed = any(
            isinstance(t, dict) and ("speed" in t or "speedAvg" in t)
            for t in active_transfers
        )
        if active_transfers and has_per_item_speed:
            speed_bytes = sum(
                float(t.get("speed") if t.get("speed") is not None else (t.get("speedAvg") or 0.0))
                for t in active_transfers
                if isinstance(t, dict)
            )
        elif active_transfers:
            speed_bytes = global_speed
        else:
            speed_bytes = 0.0 if "transferring" in data else global_speed
        speed_mb_s = speed_bytes / (1024.0 * 1024.0)
        speed_str = f"{speed_mb_s:.2f} MB/s"

        raw_eta = data.get("eta")
        eta_seconds = int(raw_eta) if raw_eta is not None else None
        eta_str = format_eta(eta_seconds)

        transfers = int(data.get("transfers", 0))
        active_transfers = data.get("transferring") or []
        total_bytes = int(data.get("bytes", 0))
        errors = int(data.get("errors", 0))

        # Determine high-level descriptive status
        if len(active_transfers) > 0:
            status_text = tr("Sincronizando (%d ativo(s)) • %s • ETA %s") % (
                len(active_transfers),
                speed_str,
                eta_str,
            )
        elif errors > 0:
            status_text = tr("Ocioso com %d erro(s)") % errors
        else:
            status_text = tr("Sincronizado / Ocioso")

        return StatsData(
            is_online=True,
            speed_bytes_per_sec=speed_bytes,
            speed_mb_s=speed_mb_s,
            speed_str=speed_str,
            eta_seconds=eta_seconds,
            eta_str=eta_str,
            transfers_count=transfers,
            total_bytes_transferred=total_bytes,
            total_bytes_str=format_bytes(total_bytes),
            errors_count=errors,
            status_text=status_text,
            active_transfers=active_transfers,
            raw_data=data,
        )

    return StatsData(is_online=False, status_text=tr("Drive não conectado"))


def fetch_rclone_transferred(creds: RCCredentials, timeout: float = 2.0) -> List[Dict[str, Any]]:
    """
    Executes a query to `/core/transferred` via RC.

    Args:
        creds: In-memory credentials for the Rclone RC API.
        timeout: Request timeout in seconds.

    Returns:
        List[Dict[str, Any]]: List of completed transfer items.
    """
    status, data = rc_request(creds, "/core/transferred", timeout=timeout)
    if status == 200 and isinstance(data, dict):
        return data.get("transferred") or []
    return []


def fetch_vfs_queue(creds: RCCredentials, timeout: float = 2.0) -> Optional[int]:
    """
    Returns how many files are still pending upload in the VFS write-back cache
    (both `uploadsInProgress` and `uploadsQueued` via `vfs/stats`, falling back to `vfs/queue`),
    or None if the RC API could not be queried.

    Blocking call: run it outside the GUI thread.
    """
    status, data = rc_request(creds, "/vfs/stats", timeout=timeout)
    if status == 200 and isinstance(data, dict):
        disk_cache = data.get("diskCache")
        if isinstance(disk_cache, dict):
            in_prog = int(disk_cache.get("uploadsInProgress") or 0)
            queued = int(disk_cache.get("uploadsQueued") or 0)
            return in_prog + queued

    status_q, data_q = rc_request(creds, "/vfs/queue", timeout=timeout)
    if status_q == 200 and isinstance(data_q, dict):
        return len(data_q.get("queue") or [])

    return None


def fetch_vfs_stats(creds: RCCredentials, timeout: float = 2.0) -> Dict[str, Any]:
    """
    Queries `/vfs/stats` via RC and returns detailed diskCache and queue metadata:
    - uploadsInProgress (int)
    - uploadsQueued (int)
    - bytesUsed (int)
    - totalBytes (int)
    """
    status, data = rc_request(creds, "/vfs/stats", timeout=timeout)
    result = {
        "uploadsInProgress": 0,
        "uploadsQueued": 0,
        "bytesUsed": 0,
        "totalBytes": 0,
        "raw": data if status == 200 else {},
    }
    if status == 200 and isinstance(data, dict):
        disk_cache = data.get("diskCache")
        if isinstance(disk_cache, dict):
            result["uploadsInProgress"] = int(disk_cache.get("uploadsInProgress") or 0)
            result["uploadsQueued"] = int(disk_cache.get("uploadsQueued") or 0)
            result["bytesUsed"] = int(disk_cache.get("bytesUsed") or 0)
            result["totalBytes"] = int(disk_cache.get("totalBytes") or 0)
    return result


def rc_vfs_refresh(
    creds: RCCredentials,
    timeout: float = 15.0,
    recursive: bool = False,
    async_mode: bool = False,
) -> bool:
    """
    Sends a POST request to `/vfs/refresh` via RC to reload the directory cache
    without unmounting. Blocking call unless `async_mode=True`: run outside the GUI thread.
    """
    payload: Dict[str, Any] = {}
    if recursive:
        payload["recursive"] = "true"
    if async_mode:
        payload["_async"] = True
    if payload:
        status, _ = rc_request(creds, "/vfs/refresh", payload, timeout=timeout)
    else:
        status, _ = rc_request(creds, "/vfs/refresh", timeout=timeout)
    return status == 200


def rc_vfs_forget(creds: RCCredentials, timeout: float = 5.0) -> bool:
    """
    Sends a POST request to `/vfs/forget` via RC to drop unreferenced cached directory
    and file entries, reclaiming SSD memory immediately without unmounting.
    """
    status, _ = rc_request(creds, "/vfs/forget", timeout=timeout)
    return status == 200


def set_rc_bwlimit(creds: RCCredentials, rate: str, timeout: float = 5.0) -> bool:
    """
    Sets the active bandwidth limit on the running rclone daemon via RC `/core/bwlimit`.

    Blocking call: run it outside the GUI thread.
    """
    status, _ = rc_request(creds, "/core/bwlimit", {"rate": rate}, timeout=timeout)
    return status == 200


class RcloneStatsPoller(QThread):
    """
    Dedicated background worker thread that polls Rclone RC `/core/stats`
    every 1 second and tracks the VFS write-back upload queue.
    """

    stats_updated = Signal(object)  # Emits StatsData instance
    connection_lost = Signal()

    def __init__(
        self,
        credentials: RCCredentials,
        poll_interval: float = 1.0,
        parent: Optional[Any] = None,
        daemon: Optional[Any] = None,
    ) -> None:
        super().__init__(parent)
        self.credentials = credentials
        self.poll_interval = poll_interval
        self.daemon = daemon
        self._running = False
        self._recent_transfers: deque[Dict[str, Any]] = deque(maxlen=10)
        self._seen_transfers_keys: set[str] = set()

    def _is_daemon_mount_alive(self) -> bool:
        """Checks whether the underlying rclone daemon process and mount point are still active."""
        if self.daemon is None:
            return False
        try:
            return bool(self.daemon.is_running() and is_path_mounted(self.daemon.mount_point))
        except Exception:
            return False

    def run(self) -> None:
        """Main polling loop with adaptive intervals to avoid VFS lock contention during browsing."""
        self._running = True
        endpoint_label = self.credentials.socket_path or self.credentials.url
        logger.info("Started stats polling thread for %s", endpoint_label)

        was_online = False
        consecutive_failures = 0
        last_valid_stats: Optional[StatsData] = None
        vfs_queue_count = 0
        vfs_uploads_in_progress = 0
        vfs_uploads_queued = 0
        vfs_disk_cache_bytes = 0
        stalled_ticks = 0
        last_queue_check = 0.0
        last_transfers_count: Optional[int] = None
        last_errors_count: Optional[int] = None

        while self._running:
            stats = fetch_rclone_stats(self.credentials, timeout=2.5)
            if not self._running:
                break
            now = time.monotonic()
            is_busy = False

            if stats.is_online:
                consecutive_failures = 0
                was_online = True

                # Poll VFS upload queue every 2s while active/queued, or every 5s while idle.
                # Do NOT trigger on directory listings (`listed`), which causes VFS lock contention in Dolphin.
                has_live_work = len(stats.active_transfers) > 0 or vfs_queue_count > 0
                queue_interval = 2.0 if has_live_work else 5.0
                should_check_queue = (now - last_queue_check >= queue_interval) or len(stats.active_transfers) > 0

                if should_check_queue and self._running:
                    vfs_st = fetch_vfs_stats(self.credentials, timeout=2.0)
                    raw_vfs = vfs_st.get("raw") if isinstance(vfs_st, dict) else None
                    if isinstance(raw_vfs, dict) and isinstance(raw_vfs.get("diskCache"), dict):
                        vfs_uploads_in_progress = int(vfs_st["uploadsInProgress"])
                        vfs_uploads_queued = int(vfs_st["uploadsQueued"])
                        vfs_queue_count = vfs_uploads_in_progress + vfs_uploads_queued
                        vfs_disk_cache_bytes = int(vfs_st["bytesUsed"])
                    elif self._running:
                        # Fallback directly to /vfs/queue without re-querying /vfs/stats a second time
                        status_q, data_q = rc_request(self.credentials, "/vfs/queue", timeout=2.0)
                        if status_q == 200 and isinstance(data_q, dict):
                            vfs_queue_count = len(data_q.get("queue") or [])
                            vfs_uploads_queued = vfs_queue_count
                            vfs_uploads_in_progress = 0
                        if vfs_st and "bytesUsed" in vfs_st:
                            vfs_disk_cache_bytes = int(vfs_st["bytesUsed"])
                    last_queue_check = now

                    # Track recently completed file transfers only when counters change
                    if self._running and (
                        last_transfers_count is None
                        or stats.transfers_count != last_transfers_count
                        or stats.errors_count != last_errors_count
                    ):
                        last_transfers_count = stats.transfers_count
                        last_errors_count = stats.errors_count
                        transferred_items = fetch_rclone_transferred(self.credentials, timeout=2.0)
                        for item in transferred_items:
                            if not isinstance(item, dict):
                                continue
                            name = item.get("name")
                            if not name or item.get("error"):
                                continue
                            key = f"{name}_{item.get('size', 0)}_{item.get('completed_at', '')}"
                            if key not in self._seen_transfers_keys:
                                self._seen_transfers_keys.add(key)
                                self._recent_transfers.appendleft({
                                    "name": name,
                                    "size": int(item.get("size") or item.get("bytes") or 0),
                                    "completed_at": item.get("completed_at", ""),
                                })
                        if len(self._seen_transfers_keys) > 100:
                            valid_keys = {f"{it['name']}_{it['size']}_{it.get('completed_at', '')}" for it in self._recent_transfers}
                            self._seen_transfers_keys.intersection_update(valid_keys)

                stats.vfs_queue_count = vfs_queue_count
                stats.vfs_uploads_in_progress = vfs_uploads_in_progress
                stats.vfs_uploads_queued = vfs_uploads_queued
                stats.vfs_disk_cache_bytes = vfs_disk_cache_bytes
                stats.recent_transfers = list(self._recent_transfers)

                # Tag active transfers with direction (upload vs download) and detect API rate-limit stalls
                is_paused = bool(self.daemon and getattr(self.daemon, "is_user_paused", False))
                if stats.active_transfers:
                    if vfs_uploads_in_progress >= len(stats.active_transfers) and vfs_queue_count > 0:
                        direction = "upload"
                    elif vfs_uploads_in_progress == 0 and vfs_queue_count == 0:
                        direction = "download"
                    else:
                        direction = "sync"
                    for item in stats.active_transfers:
                        if isinstance(item, dict) and "direction" not in item:
                            item["direction"] = direction
                    if not is_paused and stats.speed_bytes_per_sec < 1024.0:
                        stalled_ticks += 1
                    else:
                        stalled_ticks = 0
                else:
                    stalled_ticks = 0
                stats.is_throttled = stalled_ticks >= 3

                if len(stats.active_transfers) == 0 and vfs_queue_count > 0:
                    stats.status_text = tr("Sincronizando (%d na fila) • %s • ETA %s") % (
                        vfs_queue_count,
                        stats.speed_str,
                        stats.eta_str,
                    )

                is_busy = len(stats.active_transfers) > 0 or vfs_queue_count > 0
                last_valid_stats = stats
                self.stats_updated.emit(stats)
            else:
                consecutive_failures += 1
                # If rclone is simply busy with heavy FUSE/VFS locks, do not falsely report "Offline"
                if self._is_daemon_mount_alive() and consecutive_failures < 10:
                    if last_valid_stats is not None:
                        snapshot = replace(
                            last_valid_stats,
                            recent_transfers=list(self._recent_transfers),
                            speed_bytes_per_sec=0.0 if consecutive_failures >= 2 else last_valid_stats.speed_bytes_per_sec,
                            speed_mb_s=0.0 if consecutive_failures >= 2 else last_valid_stats.speed_mb_s,
                            speed_str="0.00 MB/s" if consecutive_failures >= 2 else last_valid_stats.speed_str,
                            eta_str="--:--:--" if consecutive_failures >= 2 else last_valid_stats.eta_str,
                        )
                        self.stats_updated.emit(snapshot)
                elif consecutive_failures >= 3:
                    if was_online:
                        self.connection_lost.emit()
                        was_online = False
                    self.stats_updated.emit(stats)

            # Adaptive sleep in small increments for responsive thread termination
            sleep_interval = self.poll_interval if is_busy else max(2.0, self.poll_interval)
            steps = int(sleep_interval / 0.1)
            for _ in range(max(1, steps)):
                if not self._running:
                    break
                time.sleep(0.1)

        logger.info("Stopped stats polling thread.")

    def stop(self, wait: bool = True) -> None:
        """Stops the polling loop; optionally waits (up to 4s) for thread termination."""
        self._running = False
        if wait:
            self.wait(4000)
